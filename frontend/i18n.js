export function getUi(lang) {
  return ui[lang] || ui.ru;
}

export function getLocalizedCourse(course, lang) {
  if (lang !== 'kk') return course;
  const courseText = courseTranslations.kk[course.id] || {};
  return {
    ...course,
    title: courseText.title || course.title,
    category: courseText.category || course.category,
    description: courseText.description || course.description,
    lessons: course.lessons.map((lesson) => ({
      ...lesson,
      title: lessonTitles.kk[lesson.id] || lesson.title
    }))
  };
}
